"""Build the tiny first-paint images from the same verified office plates as the renderer."""
import base64
import hashlib
import io
import json
import re
from pathlib import Path

from PIL import Image

plugin = Path(__file__).resolve().parents[1]
client = plugin.parents[1] / 'overlays/deepseek-harness/luma-full/files/packages/client/ui-brand-official/src/client/office2d'
entries = json.loads((plugin / 'lib/asset-manifest.json').read_text(encoding='utf-8'))
phases = ('morning', 'noon', 'afternoon', 'dusk', 'night', 'closed')
rooms = {'classic': 'office-world-{}-v2'}
for role in ('duanmu-yan', 'lu-mi', 'bai-shuangming'):
    rooms['office.' + role + '.v1'] = 'office-theme-' + role + '-{}-v1'
for role in ('jingyuniang', 'claude', 'longmama', 'gemini', 'grok'):
    rooms['office.' + role + '.v1'] = 'office-' + role + '-{}'
encoded = {}
for theme, prefix in rooms.items():
    encoded[theme] = {}
    for phase in phases:
        pattern = re.escape('luma-office/assets/' + prefix.format(phase)) + r'\.[0-9a-f]{12}\.png'
        row, = (r for r in entries if re.fullmatch(pattern, r['path']))
        raw = (plugin / 'public' / row['path']).read_bytes()
        if hashlib.sha256(raw).hexdigest() != row['sha256']:
            raise ValueError('Unverified office plate ' + row['path'])
        with Image.open(io.BytesIO(raw)) as plate:
            plate.thumbnail((96, 54), Image.Resampling.LANCZOS)
            webp = io.BytesIO()
            plate.convert('RGB').save(webp, format='WEBP', quality=45, method=6)
        encoded[theme][phase] = 'data:image/webp;base64,' + base64.b64encode(webp.getvalue()).decode('ascii')
output = '// Generated by modules/luma-dsh-plugin/scripts/prepare-office-previews.py.\n'
output += 'export const OFFICE_SCENE_PREVIEWS: Readonly<Record<string, Readonly<Record<string, string>>>> = '
(client / 'officeScenePreviews.generated.ts').write_text(output + json.dumps(encoded, indent=2) + '\n', encoding='utf-8', newline='\n')
